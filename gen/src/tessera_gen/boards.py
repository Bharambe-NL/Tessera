"""Pre-built boards. Doc 02 section 7.

"Twenty boards, generated at T1."

These evaluate the agents that read existing state rather than produce it: the
Exercise agent (items must trace to cards), the Reader (structure recovered from
a raster), block spawning (the composed question must reference the parent
context), and bundle import (merge rules from doc 01 section 7).

The ink is the part worth explaining. Doc 02 section 7 asks for hand drawn tables
and box and arrow diagrams "generated by a path renderer from a structured
description, with the structure recorded as ground truth for the Reader". So the
strokes are drawn *from* a known table or graph, and that known structure is what
the Reader's F1 is scored against. A sketch with no recorded structure would be
untestable.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field

from .corpus import Document
from .facts import Fact
from .questions import Question
from .rng import Rng

BOARD_COUNT = 20

#: Doc 02 section 7's shares.
INK_SHARE = 0.5
SKETCH_STRUCTURE_SHARE = 0.25
IMAGE_SHARE = 0.25
FLAGGED_BOARDS = 2
REVIEWED_BOARDS = 1
BUNDLE_BOARDS = 3
#: Doc 15 section 3 excludes a trashed board from memory. One board is trashed so
#: the exclusion has something to exclude, which is the difference between the
#: rule being implemented and the rule being tested.
TRASHED_BOARDS = 1


@dataclass
class Card:
    card_id: str
    parent_card_id: str | None
    kind: str
    question: str
    depth: str
    answer: str
    findings: list[dict] = field(default_factory=list)
    visual: dict | None = None
    citations: list[dict] = field(default_factory=list)
    anchor_text: str | None = None
    status: str = "done"
    #: Doc 01 section 4.4. Prior verified cards this one was built from, as
    #: {board_id, card_id, verified_at}. Doc 15 section 2: context, never
    #: evidence, so a card that builds on another still cites the original.
    builds_on: list[dict] = field(default_factory=list)
    #: Doc 15 section 3, computed once the flags and the trashed board are known.
    #: The boards retriever may recall this card.
    memory_eligible: bool = False
    confidence: float = 0.0
    #: The facts this card's answer states, so an Exercise item can be checked
    #: against ground truth rather than against the prose.
    fact_ids: list[str] = field(default_factory=list)


@dataclass
class Stroke:
    colour: str
    width: float
    points: list[tuple[int, int]]


@dataclass
class SketchTruth:
    """What the ink actually draws. Doc 02 section 7: the Reader's ground truth."""

    kind: str  # table | diagram
    columns: list[str] = field(default_factory=list)
    rows: list[list[str]] = field(default_factory=list)
    nodes: list[dict] = field(default_factory=list)
    edges: list[dict] = field(default_factory=list)


@dataclass
class Board:
    board_id: str
    title: str
    cards: list[Card] = field(default_factory=list)
    concepts: list[dict] = field(default_factory=list)
    ink: list[Stroke] = field(default_factory=list)
    notes: list[dict] = field(default_factory=list)
    images: list[dict] = field(default_factory=list)
    flags: list[dict] = field(default_factory=list)
    reviews: list[dict] = field(default_factory=list)
    sketch_truth: SketchTruth | None = None
    export_as_bundle: bool = False
    #: Doc 15 section 3: a trashed board is never recalled from.
    trashed: bool = False
    #: Doc 02 section 7: one bundle collides on a Concept term with the
    #: importing profile, so doc 01 section 7's merge rule gets exercised.
    concept_collision: str | None = None
    snapshot: str = "T1"

    def to_json(self) -> dict:
        out = asdict(self)
        out["ink"] = [asdict(s) for s in self.ink]
        out["sketch_truth"] = asdict(self.sketch_truth) if self.sketch_truth else None
        return out


# --------------------------------------------------------------- ink drawing --


def draw_table(
    rng: Rng, columns: list[str], rows: list[list[str]]
) -> tuple[list[Stroke], SketchTruth]:
    """Strokes that look like a table someone drew by hand.

    The lines wobble, because a ruler straight line is not what the Reader will
    meet and a recogniser tuned on one would not survive the other.
    """
    strokes: list[Stroke] = []
    left, top = 80, 80
    col_w, row_h = 180, 54
    cols = len(columns)
    total_rows = len(rows) + 1

    def wobble(v: int) -> int:
        return v + rng.randint(-3, 3)

    for r in range(total_rows + 1):
        y = top + r * row_h
        points = [(wobble(left + i * 30), wobble(y)) for i in range((cols * col_w) // 30 + 1)]
        strokes.append(Stroke(colour="ink", width=2.2, points=points))

    for c in range(cols + 1):
        x = left + c * col_w
        points = [(wobble(x), wobble(top + i * 18)) for i in range((total_rows * row_h) // 18 + 1)]
        strokes.append(Stroke(colour="ink", width=2.2, points=points))

    return strokes, SketchTruth(kind="table", columns=columns, rows=rows)


def draw_diagram(
    rng: Rng, nodes: list[str], edges: list[tuple[int, int]]
) -> tuple[list[Stroke], SketchTruth]:
    """Boxes and arrows, drawn from a known graph."""
    strokes: list[Stroke] = []
    positions: list[tuple[int, int]] = []

    for i, _ in enumerate(nodes):
        x = 120 + (i % 3) * 240
        y = 120 + (i // 3) * 180
        positions.append((x, y))
        w, h = 160, 70

        def wobble(v: int) -> int:
            return v + rng.randint(-2, 2)

        box = [
            *[(wobble(x + step), wobble(y)) for step in range(0, w, 20)],
            *[(wobble(x + w), wobble(y + step)) for step in range(0, h, 18)],
            *[(wobble(x + w - step), wobble(y + h)) for step in range(0, w, 20)],
            *[(wobble(x), wobble(y + h - step)) for step in range(0, h, 18)],
        ]
        strokes.append(Stroke(colour="ink", width=2.4, points=box))

    for a, b in edges:
        (ax, ay), (bx, by) = positions[a], positions[b]
        line = [
            (ax + 160, ay + 35),
            ((ax + bx) // 2 + 80, (ay + by) // 2 + 35 + rng.randint(-6, 6)),
            (bx, by + 35),
        ]
        strokes.append(Stroke(colour="ink", width=2.0, points=line))
        # The arrow head, so a recogniser can tell direction.
        strokes.append(
            Stroke(
                colour="ink",
                width=2.0,
                points=[(bx - 12, by + 28), (bx, by + 35), (bx - 12, by + 42)],
            )
        )

    return strokes, SketchTruth(
        kind="diagram",
        nodes=[{"id": f"n{i}", "label": label} for i, label in enumerate(nodes)],
        edges=[{"from": f"n{a}", "to": f"n{b}"} for a, b in edges],
    )


# ------------------------------------------------------------------ building --


def _answer_for(fact: Fact, ordinal: int) -> str:
    return f"{fact.statement} [{ordinal}]"


def _visual_for(fact: Fact, cards_seen: int) -> dict:
    """A visual whose blocks trace to the fact, so the Exercise agent's
    traceability check has something real to walk."""
    label = fact.value.get("label") or fact.value.get("term") or "The requirement"
    value = fact.display_value
    if fact.kind in ("number", "date"):
        return {
            "type": "table",
            "title": f"{label.capitalize()}",
            "payload": {
                "columns": ["Item", "Value"],
                "rows": [[label, value]],
            },
            "block_index": [
                {"ref": "/columns/0", "label": "Item", "citation_ordinals": [], "no_claim": True},
                {"ref": "/columns/1", "label": "Value", "citation_ordinals": [], "no_claim": True},
                {"ref": "/rows/0/0", "label": label, "citation_ordinals": [1]},
                {"ref": "/rows/0/1", "label": value, "citation_ordinals": [1]},
            ],
        }
    steps = fact.value.get("steps") or [fact.value.get("text", "the requirement")]
    return (
        {
            "type": "steps",
            "title": f"How {label} works",
            "payload": {"steps": [{"label": s[:40]} for s in steps]},
            "block_index": [
                {"ref": f"/steps/{i}", "label": s[:40], "citation_ordinals": [1]}
                for i, s in enumerate(steps)
            ],
        }
        if cards_seen % 2
        else {
            "type": "list",
            "title": f"{label.capitalize()}",
            "payload": {
                "groups": [
                    {
                        "heading": "What applies",
                        "items": [{"name": str(fact.value.get("text", label))[:60]}],
                    }
                ]
            },
            "block_index": [
                {
                    "ref": "/groups/0/heading",
                    "label": "What applies",
                    "citation_ordinals": [],
                    "no_claim": True,
                },
                {
                    "ref": "/groups/0/items/0",
                    "label": str(fact.value.get("text", label))[:60],
                    "citation_ordinals": [1],
                },
            ],
        }
    )


def generate(
    seed: int,
    facts: list[Fact],
    documents: list[Document],
    questions: list[Question],
) -> list[Board]:
    """Twenty boards at T1."""
    rng = Rng(seed, "boards")
    by_fact = {f.fact_id: f for f in facts}
    by_doc = {d.doc_id: d for d in documents}
    roots = [
        q for q in questions if q.parent_q_id is None and q.required_facts and q.required_sources
    ]

    boards: list[Board] = []
    for index in range(BOARD_COUNT):
        b_rng = rng.derive(str(index))
        board = Board(board_id=f"B-{index + 1:02d}", title="", snapshot="T1")

        card_count = b_rng.randint(4, 12)
        seeds = [roots[(index * 7 + i) % len(roots)] for i in range(card_count)]
        board.title = seeds[0].text

        # A tree of depth 2 to 4: roots, follows beneath, branches to the side.
        depth_target = b_rng.randint(2, 4)
        parents: list[str | None] = [None]

        for i, q in enumerate(seeds):
            fact = by_fact.get(q.required_facts[0])
            if fact is None:
                continue
            parent = (
                parents[i % len(parents)] if i and len(parents) > 1 else (parents[0] if i else None)
            )
            kind = "root" if parent is None else ("branch" if b_rng.chance(0.3) else "follow")
            card_id = f"{board.board_id}-C{i + 1:02d}"

            source_id = q.required_sources[0]
            doc = by_doc.get(source_id)
            passage = next(
                (
                    p
                    for p in (doc.passages if doc else [])
                    if any(fid == fact.fact_id for fid, _ in p.plants)
                ),
                None,
            )

            card = Card(
                card_id=card_id,
                parent_card_id=parent,
                kind=kind,
                question=q.text,
                depth=q.depth_expected,
                answer=_answer_for(fact, 1),
                findings=[{"text": fact.statement, "citations": [1]}],
                visual=_visual_for(fact, i),
                citations=[
                    {
                        "ordinal": 1,
                        "source_title": doc.title if doc else "A source",
                        "source_class": {
                            "regulatory": "regulatory",
                            "internal": "local_document",
                            "web": "web",
                        }.get(doc.kind if doc else "web", "web"),
                        "locator": doc.path if doc else "",
                        "passage_id": passage.passage_id if passage else "",
                        "verdict": "supported",
                    }
                ],
                anchor_text=q.anchor_text,
                confidence=round(0.55 + b_rng.random() * 0.4, 2),
                fact_ids=[fact.fact_id],
            )
            board.cards.append(card)
            if len(parents) < depth_target:
                parents.append(card_id)

        # ---- concepts ------------------------------------------------------
        # Doc 02 section 7: 2 to 5 confirmed and 2 to 5 proposed.
        concept_ids = sorted(
            {c for card in board.cards for fid in card.fact_ids for c in by_fact[fid].concept_ids}
        )
        for cid in concept_ids[: b_rng.randint(2, 5)]:
            board.concepts.append(
                {
                    "concept_id": f"{board.board_id}-{cid}",
                    "term": cid.replace("-", " "),
                    "status": "confirmed",
                    "linked_cards": [c.card_id for c in board.cards[:2]],
                }
            )
        for i in range(b_rng.randint(2, 5)):
            board.concepts.append(
                {
                    "concept_id": f"{board.board_id}-proposed-{i}",
                    "term": f"proposed term {i}",
                    "status": "proposed",
                    "linked_cards": [],
                }
            )

        # ---- authored material ---------------------------------------------
        if b_rng.chance(INK_SHARE):
            if b_rng.chance(SKETCH_STRUCTURE_SHARE / INK_SHARE):
                if b_rng.chance(0.5):
                    columns = ["Rule", "Value"]
                    rows = [
                        [
                            by_fact[c.fact_ids[0]].value.get("label", "item")[:20],
                            by_fact[c.fact_ids[0]].display_value,
                        ]
                        for c in board.cards[:3]
                        if c.fact_ids
                    ]
                    board.ink, board.sketch_truth = draw_table(b_rng.derive("ink"), columns, rows)
                else:
                    nodes = [c.question[:22] for c in board.cards[:4]]
                    edges = [(0, 1), (1, 2)][: max(len(nodes) - 1, 1)]
                    board.ink, board.sketch_truth = draw_diagram(b_rng.derive("ink"), nodes, edges)
            else:
                # Unstructured scribble: no recorded truth, so nothing scores it.
                board.ink = [
                    Stroke(
                        "ink",
                        2.0,
                        [
                            (b_rng.randint(60, 700), b_rng.randint(60, 500))
                            for _ in range(b_rng.randint(6, 18))
                        ],
                    )
                    for _ in range(b_rng.randint(1, 4))
                ]
            board.notes.append(
                {
                    "text": "Check this against the register before the next review.",
                    "colour": "amber",
                    "position": {"x": 720, "y": 120, "w": 220, "h": 120},
                }
            )

        if b_rng.chance(IMAGE_SHARE):
            # Doc 02 section 7: rendered tables and slides with the underlying
            # data recorded, so the Reader can be scored on what it recovered.
            rows = [
                [
                    by_fact[c.fact_ids[0]].value.get("label", "item")[:24],
                    by_fact[c.fact_ids[0]].display_value,
                ]
                for c in board.cards[:4]
                if c.fact_ids
            ]
            board.images.append(
                {
                    "image_id": f"{board.board_id}-IMG1",
                    "origin": "pasted",
                    "kind": "rendered_table",
                    "underlying": {"columns": ["Item", "Value"], "rows": rows},
                    "position": {"x": 900, "y": 240},
                }
            )

        boards.append(board)

    # ---- flags, reviews and bundles ---------------------------------------
    for board in boards[:FLAGGED_BOARDS]:
        target = board.cards[0]
        board.flags.append(
            {
                "flag_id": f"{board.board_id}-F1",
                "card_id": target.card_id,
                "rule_id": "stale_source",
                "severity": "warn",
                "reason": "The cited version was superseded.",
                "status": "open",
            }
        )
        target.status = "flagged"

    for board in boards[FLAGGED_BOARDS : FLAGGED_BOARDS + REVIEWED_BOARDS]:
        target = board.cards[0]
        board.flags.append(
            {
                "flag_id": f"{board.board_id}-F1",
                "card_id": target.card_id,
                "rule_id": "length_and_format",
                "severity": "info",
                "reason": "The answer ran over its budget.",
                "status": "dismissed",
            }
        )
        board.reviews.append(
            {
                "review_id": f"{board.board_id}-R1",
                "flag_ids": [f"{board.board_id}-F1"],
                "decision": "dismiss",
                "note": "Length is fine for this card.",
            }
        )

    trashed_from = FLAGGED_BOARDS + REVIEWED_BOARDS
    for board in boards[trashed_from : trashed_from + TRASHED_BOARDS]:
        board.trashed = True

    for i, board in enumerate(boards[-BUNDLE_BOARDS:]):
        board.export_as_bundle = True
        if i == 0 and board.concepts:
            # Doc 01 section 7: on a term collision the importer keeps both,
            # marks the incoming one proposed, and links them related_to.
            board.concept_collision = board.concepts[0]["term"]

    # Doc 15 section 3: "Only verified cards remember: done, deep or research,
    # no open block flags, board not trashed." Computed last, because it reads
    # the flags and the trashed board that the loops above have just set.
    for board in boards:
        blocked = {
            f["card_id"] for f in board.flags if f["status"] == "open" and f["severity"] == "block"
        }
        for card in board.cards:
            card.memory_eligible = (
                card.status == "done"
                and card.depth in ("deep", "research")
                and card.card_id not in blocked
                and not board.trashed
            )

    return boards


def summarise(boards: list[Board]) -> dict:
    return {
        "total": len(boards),
        "cards": sum(len(b.cards) for b in boards),
        "with_ink": sum(1 for b in boards if b.ink),
        "with_sketch_truth": sum(1 for b in boards if b.sketch_truth),
        "with_images": sum(1 for b in boards if b.images),
        "with_open_flags": sum(1 for b in boards if any(f["status"] == "open" for f in b.flags)),
        "with_reviews": sum(1 for b in boards if b.reviews),
        "bundles": sum(1 for b in boards if b.export_as_bundle),
        "concept_collisions": sum(1 for b in boards if b.concept_collision),
        "trashed": sum(1 for b in boards if b.trashed),
        "memory_eligible_cards": sum(1 for b in boards for c in b.cards if c.memory_eligible),
    }
